<?php
declare(strict_types=1);

namespace WMCyber\Newsletter\Core;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

use WMCyber\Newsletter\Database\Schema;
use WMCyber\Newsletter\Queue\SyncQueue;

final class Activator {
	public static function activate( bool $network_wide = false ): void {
		if ( $network_wide && function_exists( 'is_multisite' ) && is_multisite() && function_exists( 'get_sites' ) ) {
			$site_ids = get_sites( [
				'fields' => 'ids',
				'number' => 0,
			] );
			if ( is_array( $site_ids ) && [] !== $site_ids ) {
				foreach ( $site_ids as $site_id ) {
					switch_to_blog( (int) $site_id );
					try {
						self::activate_site();
					} finally {
						restore_current_blog();
					}
				}
				return;
			}
		}

		self::activate_site();
	}

	private static function activate_site(): void {
		Schema::create_tables();

		// Default options if not present. The two secrets (proof-of-work key, webhook key) are
		// generated by SettingsManager on first read and stored there.
		if ( ! get_option( 'wm_newsletter_settings' ) ) {
			update_option( 'wm_newsletter_settings', [
				'active_provider'     => 'local',
				'doi_ttl_hours'       => 48,
				'sender_name'         => get_bloginfo( 'name' ),
				'sender_email'        => get_option( 'admin_email' ),
				'altcha_enabled'      => 1,
				'altcha_hmac_key'     => wp_generate_password( 64, false, false ),
				'webhook_secret'      => wp_generate_password( 32, false, false ),
				'default_list_id'     => 'default',
				'enable_rfc8058'      => 1,
				'legal_notice_url'    => home_url( '/impressum/' ),
				'privacy_policy_url'  => home_url( '/datenschutz/' ),
				'doi_email_subject'   => __( 'Bitte bestätigen Sie Ihre Anmeldung', 'wm-dsgvo-newsletter-suite' ),
			], false );
		}

		// Hourly deletion of expired unconfirmed sign-ups. The five-minute sync event is scheduled by
		// SyncQueue::boot() on the next load, once its interval is registered.
		if ( ! wp_next_scheduled( SyncQueue::CLEANUP_HOOK ) ) {
			wp_schedule_event( time(), 'hourly', SyncQueue::CLEANUP_HOOK );
		}
	}
}
